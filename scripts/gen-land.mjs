// Generates src/data/land.ts: Natural Earth 110m land (public domain) as compact polygons in 0.1 degree units:
// x = (lon + 180) * 10, y = (90 - lat) * 10. Run from a folder that has world-atlas and topojson-client installed:
//   cd /tmp/geo-gen && node <repo>/scripts/gen-land.mjs <repo>/src/data/land.ts
import fs from "node:fs";
import path from "node:path";
import { createRequire } from "node:module";
const require = createRequire(path.join(process.cwd(), "noop.js"));
const { feature } = require("topojson-client");
const topo = require("world-atlas/land-110m.json");
const land = feature(topo, topo.objects.land);
const polys = land.features ? land.features.flatMap((f) => f.geometry.coordinates) : land.geometry.coordinates;
const rings = [];
for (const poly of polys) {
	for (const ring of poly) {
		const raw = ring.map(([lon, lat]) => [(lon + 180) * 10, (90 - lat) * 10]);
		let q;
		if (raw.some(([, y]) => y >= 1799.5)) {
			// polar ring (Antarctica): drop points on the pole line and close along the bottom edge
			q = [...raw.filter(([, y]) => y < 1799.5), [3600, 1800], [0, 1800]];
		} else {
			// unwrap antimeridian jumps so the ring stays continuous (the renderer draws 3 copies)
			q = [raw[0]];
			let shift = 0;
			for (let i = 1; i < raw.length; i++) {
				const dx = raw[i][0] - raw[i - 1][0];
				if (dx > 1800) shift -= 3600;
				else if (dx < -1800) shift += 3600;
				q.push([raw[i][0] + shift, raw[i][1]]);
			}
		}
		q = q.map(([x, y]) => [Math.round(x), Math.round(y)]).filter((pt, i, a) => !i || pt[0] !== a[i - 1][0] || pt[1] !== a[i - 1][1]);
		if (q.length >= 4) rings.push(q);
	}
}
// delta encode: "x,y;dx,dy;dx,dy|..." keeps the file small and trivially parseable
const enc = rings.map((q) => {
	let px = q[0][0], py = q[0][1];
	const parts = [`${px},${py}`];
	for (let i = 1; i < q.length; i++) { parts.push(`${q[i][0] - px},${q[i][1] - py}`); px = q[i][0]; py = q[i][1]; }
	return parts.join(";");
}).join("|");
const out = process.argv[2];
fs.writeFileSync(out, `// Generated by scripts/gen-land.mjs from Natural Earth 110m land (public domain). Do not edit.\n// Rings separated by "|", points by ";", first point absolute then deltas, units of 0.1 degree: x=(lon+180)*10, y=(90-lat)*10.\nexport const LAND = ${JSON.stringify(enc)};\n`);
console.log("rings:", rings.length, "bytes:", enc.length);

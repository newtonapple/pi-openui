// Writes src/diagram/wide.ts: the code points pi draws two cells wide, taken from pi's own width function (visibleWidth), so
// our grid and the terminal agree on where every cell is. The emoji blocks of this table are corrected against the running pi
// when the extension loads (src/pi/widths.ts), so it is upkeep, not a must: test/width.test.ts reports a table that is a Unicode
// release behind as a warning, and fails only for the blocks nothing corrects.
//
//   npm run width
import { writeFileSync } from "node:fs";

const tui: any = await import("@earendil-works/pi-tui");
const wide: number[] = [];
for (let cp = 0x20; cp <= 0x10ffff; cp++) {
	if (cp >= 0xd800 && cp <= 0xdfff) continue;
	if (tui.visibleWidth(String.fromCodePoint(cp)) === 2) wide.push(cp);
}
const pairs: string[] = [];
let start = wide[0];
let prev = wide[0];
for (const cp of [...wide.slice(1), -1]) {
	if (cp !== prev + 1) {
		pairs.push(`0x${start.toString(16)}, 0x${prev.toString(16)}`);
		start = cp;
	}
	prev = cp;
}
const rows: string[] = [];
for (let i = 0; i < pairs.length; i += 4) rows.push(`\t${pairs.slice(i, i + 4).join(", ")},`);
writeFileSync(
	new URL("../src/diagram/wide.ts", import.meta.url),
	`// Generated by scripts/width-table.ts from pi's own width function: do not edit. Run \`npm run width\` to refresh it (the extension corrects its emoji blocks from the running pi when it loads).
// The code points pi draws two cells wide, as inclusive [first, last] pairs in ascending order.
export const WIDE: readonly number[] = [
${rows.join("\n")}
];
`,
);
console.log(`${wide.length} wide code points in ${pairs.length} ranges`);
